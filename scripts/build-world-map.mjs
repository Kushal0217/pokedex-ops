// Generates src/features/flights/worldMap.generated.ts: world land as one SVG
// path in a plain equirectangular projection (x = lon + 180, y = 90 - lat),
// from Natural Earth 1:110m land (public domain) via the world-atlas package.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const require = createRequire(import.meta.url);
const topojson = require('topojson-client');
const land = topojson.feature(require('world-atlas/land-110m.json'), require('world-atlas/land-110m.json').objects.land);

const polygons = land.features.flatMap((f) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates));
const fmt = (n) => String(Math.round(n * 10) / 10);
let d = '';
for (const polygon of polygons) {
  for (const ring of polygon) {
    // Skip Antarctica: it adds weight and no airports.
    if (ring.every(([, lat]) => lat < -60)) continue;
    // A ring that crosses the antimeridian would draw a line across the whole map:
    // start a new subpath at each such jump instead (fill closes each piece on its own).
    let split = false;
    d += ring
      .map(([lon, lat], i) => {
        const jump = i > 0 && Math.abs(lon - ring[i - 1][0]) > 180;
        if (jump) split = true;
        return `${i === 0 || jump ? 'M' : 'L'}${fmt(lon + 180)} ${fmt(90 - lat)}`;
      })
      .join('');
    if (!split) d += 'Z';
  }
}
writeFileSync(
  'src/features/flights/worldMap.generated.ts',
  `// Generated by scripts/build-world-map.mjs. Do not edit by hand.\n// Natural Earth 1:110m land (public domain). Equirectangular: x = lon + 180, y = 90 - lat.\nexport const WORLD_LAND_PATH =\n  '${d}';\n`,
);
console.log(`Wrote world map path (${(d.length / 1024).toFixed(1)} kB)`);
